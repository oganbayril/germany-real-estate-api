"""The Alembic migrations must stay in sync with the ORM models."""

from __future__ import annotations

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect

from realestate.config import get_settings

PROJECT_ROOT = Path(__file__).resolve().parents[1]


@pytest.fixture
def alembic_config(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Config:
    db_url = f"sqlite+pysqlite:///{(tmp_path / 'migrations.db').as_posix()}"
    monkeypatch.setenv("RE_DATABASE_URL", db_url)
    get_settings.cache_clear()
    monkeypatch.chdir(PROJECT_ROOT)
    yield Config(str(PROJECT_ROOT / "alembic.ini"))
    get_settings.cache_clear()


def test_upgrade_creates_all_tables(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    engine = create_engine(get_settings().database_url)
    tables = set(inspect(engine).get_table_names())
    engine.dispose()
    assert {"listings", "listing_price_history", "scrape_runs"} <= tables


def test_no_pending_model_changes(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    # alembic.command.check raises AutogenerateDiffsDetected if models drifted.
    command.check(alembic_config)


def test_city_name_districts_are_cleared(alembic_config: Config) -> None:
    from sqlalchemy import text

    command.upgrade(alembic_config, "a7c3d9e2f4b1")
    engine = create_engine(get_settings().database_url)
    with engine.begin() as conn:
        for i, (city, district) in enumerate(
            [("berlin", "Berlin"), ("koeln", "Köln"), ("berlin", "Pankow"), ("hamburg", None)]
        ):
            conn.execute(
                text(
                    "INSERT INTO listings (expose_id, city, district, property_type,"
                    " listing_status, first_seen_at, last_seen_at)"
                    " VALUES (:e, :c, :d, 'apartment', 'active', CURRENT_TIMESTAMP,"
                    " CURRENT_TIMESTAMP)"
                ),
                {"e": f"e{i}", "c": city, "d": district},
            )

    command.upgrade(alembic_config, "head")
    with engine.connect() as conn:
        rows = dict(conn.execute(text("SELECT expose_id, district FROM listings")).all())
    engine.dispose()
    assert rows == {"e0": None, "e1": None, "e2": "Pankow", "e3": None}
